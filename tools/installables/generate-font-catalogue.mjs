#!/usr/bin/env node
/**
 * generate-font-catalogue.mjs — regenerate the committed font catalogue from the
 * pinned ebook-fonts archives.
 *
 * The "Install additional fonts" feature needs to know every font family (and
 * its .ttf files) *before* any archive is downloaded: the "Select fonts" dialog
 * lists the families, and removal detection needs the on-device file names. The
 * archives themselves are gitignored, so this script derives that catalogue from
 * the two locked zips in src/assets and writes it to
 * src/js/nickelmenu/features/additional-fonts/catalogue.js (committed).
 *
 * Run after `npm run update:installables` bumps the ebook-fonts archives (the
 * update script chains this automatically). `--check` regenerates in memory and
 * fails when the committed catalogue no longer matches the locked archives.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';
import prettier from 'prettier';

const APP_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const LOCK_PATH = join(APP_DIR, 'installables.lock');
const ASSETS_DIR = join(APP_DIR, 'src', 'assets');
const CATALOGUE_PATH = join(APP_DIR, 'src', 'js', 'nickelmenu', 'features', 'additional-fonts', 'catalogue.js');

// The two collections the ebook-fonts release ships for Kobo. `installable` is
// the installables.lock id; `asset` the served archive name.
const COLLECTIONS = [
    { id: 'core', title: 'Core fonts', installable: 'ebook-fonts-core', asset: 'kobo-core-fonts.zip' },
    { id: 'extra', title: 'Extra fonts', installable: 'ebook-fonts-extra', asset: 'kobo-extra-fonts.zip' },
];

// Every file in the archives must look like KF_<Family>-<Weight>.ttf. Anything
// else means the upstream layout changed and a human should look at it.
const FONT_FILE_PATTERN = /^KF_([A-Za-z0-9_]+)-(Regular|Italic|Bold|BoldItalic)\.ttf$/;
const WEIGHT_ORDER = ['Regular', 'Italic', 'Bold', 'BoldItalic'];

async function collectFamilies(collection) {
    const zipPath = join(ASSETS_DIR, collection.asset);
    if (!existsSync(zipPath)) {
        throw new Error(`${collection.asset} not found in src/assets — run \`npm run setup:installables\` first.`);
    }

    const zip = await JSZip.loadAsync(await readFile(zipPath));
    const byPrefix = new Map();
    for (const [name, entry] of Object.entries(zip.files)) {
        if (entry.dir) throw new Error(`${collection.asset}: unexpected directory entry ${name}`);
        const match = name.match(FONT_FILE_PATTERN);
        if (!match) throw new Error(`${collection.asset}: unexpected file ${name} (expected KF_<Family>-<Weight>.ttf)`);
        const [, prefix] = match;
        if (!byPrefix.has(prefix)) byPrefix.set(prefix, []);
        byPrefix.get(prefix).push(name);
    }

    const families = [];
    for (const [prefix, files] of byPrefix) {
        if (!files.includes(`KF_${prefix}-Regular.ttf`)) {
            throw new Error(`${collection.asset}: family ${prefix} has no Regular weight`);
        }
        const name = prefix.replace(/_/g, ' ');
        families.push({
            id: prefix.toLowerCase().replace(/_/g, '-'),
            name,
            collection: collection.id,
            files: files.sort((a, b) => WEIGHT_ORDER.indexOf(a.match(FONT_FILE_PATTERN)[2]) - WEIGHT_ORDER.indexOf(b.match(FONT_FILE_PATTERN)[2])),
        });
    }
    families.sort((a, b) => a.name.localeCompare(b.name));
    return families;
}

async function generate() {
    const lock = JSON.parse(await readFile(LOCK_PATH, 'utf8'));
    const versions = COLLECTIONS.map((c) => lock.installables[c.installable]?.version ?? 'unknown');
    const version = [...new Set(versions)].join(' / ');

    const families = [];
    const seen = new Map();
    for (const collection of COLLECTIONS) {
        for (const family of await collectFamilies(collection)) {
            if (seen.has(family.id)) {
                throw new Error(`family ${family.id} appears in both ${seen.get(family.id)} and ${family.collection}`);
            }
            seen.set(family.id, family.collection);
            families.push(family);
        }
    }

    const source = `/**
 * catalogue.js — the ebook-fonts collection shipped by "Install additional fonts".
 *
 * GENERATED by tools/installables/generate-font-catalogue.mjs from the pinned
 * ebook-fonts archives (${version}) — do not edit by hand. Regenerate with
 * \`npm run update:installables\` (or run the generator directly) after the
 * archives change.
 *
 * Each family lists the exact .ttf files inside the collection archive, which
 * are also the file names installed into fonts/ on the device. A family's
 * on-device display name is "KF " + its name (the fonts' internal family name).
 */

export const FONT_COLLECTIONS = ${JSON.stringify(COLLECTIONS, null, 4)};

export const FONT_FAMILIES = ${JSON.stringify(families, null, 4)};
`;

    const config = (await prettier.resolveConfig(CATALOGUE_PATH)) ?? {};
    return prettier.format(source, { ...config, parser: 'babel' });
}

const check = process.argv.includes('--check');
const content = await generate();

if (check) {
    const current = existsSync(CATALOGUE_PATH) ? await readFile(CATALOGUE_PATH, 'utf8') : null;
    if (current !== content) {
        console.error('Font catalogue is out of date with the locked ebook-fonts archives.');
        console.error('Run `node tools/installables/generate-font-catalogue.mjs` and commit the result.');
        process.exit(1);
    }
    console.log('Font catalogue matches the locked ebook-fonts archives.');
} else {
    await writeFile(CATALOGUE_PATH, content);
    console.log(`Wrote ${CATALOGUE_PATH}`);
}
