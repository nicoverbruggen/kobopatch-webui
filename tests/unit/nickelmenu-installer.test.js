// --- buildManifest: per-feature entry shapes ---

test('buildManifest records files, directories, conf, and menuItems-only features', async () => {
    const installer = new NickelMenuInstaller();
    const withFiles = { id: 'with-files', title: 'With Files', install: () => [{ path: 'f1', data: 'x' }] };
    const menuOnly = { id: 'menu-only', title: 'Menu Only', menuItems: () => [] };
    const withDirs = { id: 'with-dirs', title: 'With Dirs', directories: [['adds', 'thing']] };
    const withConf = {
        id: 'with-conf',
        title: 'With Conf',
        confSettings: () => [{ section: 'S', key: 'k', value: 'v', revertable: true, revertTo: 'old' }],
    };
    const features = [withFiles, menuOnly, withDirs, withConf];

    const { files, featureFiles } = await installer.collectFiles(features, () => {});
    const manifest = installer.buildManifest(features, files, featureFiles, null, null);

    assert.deepEqual(manifest.selected, ['with-files', 'menu-only', 'with-dirs', 'with-conf']);
    assert.deepEqual(manifest.features['with-files'].files, [{ path: 'f1', type: 'file' }]);
    // A feature that only contributes menu items owns no files of its own.
    assert.deepEqual(manifest.features['menu-only'].files, []);
    // directories short-circuit the files list entirely.
    assert.deepEqual(manifest.features['with-dirs'].directories, [['adds', 'thing']]);
    assert.equal(manifest.features['with-dirs'].files, undefined);
    // Only revertable conf settings are recorded, with revertTo carried through.
    assert.deepEqual(manifest.features['with-conf'].conf, [{ section: 'S', key: 'k', value: 'v', revertTo: 'old' }]);
});
