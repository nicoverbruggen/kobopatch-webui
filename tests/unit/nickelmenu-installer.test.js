test('collectFiles runs postProcess in order so two features append to one shared file', async () => {
    const installer = new NickelMenuInstaller();
    // find-or-create: the first postProcess creates the file, the second must
    // see it and append rather than overwrite. Second sees the first's mutation.
    const appendLine = (line) => (files) => {
        let cfg = files.find((f) => f.path === 'shared/log');
        if (!cfg) {
            cfg = { path: 'shared/log', data: 'HEADER\n' };
            files.push(cfg);
        }
        cfg.data += line + '\n';
        return files;
    };
    const a = { id: 'a', title: 'A', postProcess: appendLine('line-a') };
    const b = { id: 'b', title: 'B', postProcess: appendLine('line-b') };

    const { files } = await installer.collectFiles([a, b], () => {});

    const log = files.filter((f) => f.path === 'shared/log');
    assert.equal(log.length, 1);
    assert.equal(log[0].data, 'HEADER\nline-a\nline-b\n');
});

