const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
const { paths } = require('../../support/paths');
const { connectMockDevice, readMockFile } = require('../../support/mock-device');
const { goToNmFeatures, skipNmBackup } = require('../../support/nm-helpers');

for (const firmware of ['4.46.23852', '6.0.279225']) {
    test(`KOReader reinstall on ${firmware} replaces the old exit-hiding patch`, async ({ page }) => {
        await connectMockDevice(page, {
            firmware,
            hasKOReader: true,
            extraAddsFiles: [
                {
                    path: ['nm', 'webui-preset'],
                    content: '# Generated by KoboPatch Web UI\nmenu_item:main:KOReader:cmd_spawn:quiet:exec /mnt/onboard/.adds/koreader/koreader.sh\n',
                },
                { path: ['koreader', 'patches', '2-webui-os6-exit.lua'], content: '-- previous patch\nitem_table.exit = nil\n' },
                { path: ['koreader', 'patches', '2-personal.lua'], content: '-- keep my own patch\n' },
            ],
            extraRootFiles: [{ path: ['.kobopatch-webui', 'nickelmenu.json'], content: JSON.stringify({ selected: ['custom-menu', 'koreader'] }) }],
        });
        await goToNmFeatures(page);
        await expect(page.locator('input[name="nm-cfg-koreader"]')).toBeChecked();
        await page.click('#btn-nm-features-next');
        await skipNmBackup(page);
        await expect(page.locator('#nm-review-notices')).toContainText('Choosing Exit in KOReader will ask to restart your Kobo');
        await page.click('#btn-nm-write');
        await expect(page.locator('#step-nm-done')).toBeVisible({ timeout: 60_000 });
        expect(await readMockFile(page, '.adds', 'koreader', 'patches', '2-webui-os6-exit.lua')).toBe(
            fs.readFileSync(paths.repo('src/js/nickelmenu/features/koreader/2-webui-os6-exit.lua'), 'utf8'),
        );
        expect(await readMockFile(page, '.adds', 'koreader', 'patches', '2-personal.lua')).toBe('-- keep my own patch\n');
    });
}
