const { test, expect } = require('@playwright/test');
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const JSZip = require('jszip');
const { WEBROOT } = require('../../support/paths');
const { parseTar } = require('../../support/tar');
const { goToManualMode, connectMockDevice, readMockFile, mockPathExists } = require('../../support/mock-device');
const { goToNmFeatures, skipNmBackup } = require('../../support/nm-helpers');

const hiders = ['hide-recommendations', 'hide-row2col2', 'hide-notices'];

for (const major of ['4', '6']) {
    test(`NickelHome OS ${major} download merges the matching plugin once and writes only selected hide flags`, async ({ page }) => {
        await goToManualMode(page);
        await page.click('input[name="mode"][value="nickelmenu"]');
        await page.click('#btn-mode-next');
        await page.selectOption('#nm-manual-firmware', major);
        await page.click('#btn-nm-next');
        for (const id of hiders) await expect(page.locator(`input[name="nm-cfg-${id}"]`).locator('..').locator('.nm-config-version')).toHaveCount(0);
        await page.uncheck('input[name="nm-cfg-additional-fonts"]');
        await page.uncheck('input[name="nm-cfg-nickelmodmanager"]');
        for (const id of [hiders[0], hiders[2]]) await page.check(`input[name="nm-cfg-${id}"]`);
        await page.click('#btn-nm-features-next');
        await skipNmBackup(page);
        await expect(page.locator('#nm-review-notices')).toContainText('NickelHome');
        const [download] = await Promise.all([page.waitForEvent('download'), page.click('#btn-nm-download')]);
        const zip = await JSZip.loadAsync(fs.readFileSync(await download.path()));
        const filename = major === '6' ? 'Kobo.tgz' : 'KoboRoot.tgz';
        const pluginPath = (major === '6' ? '' : 'usr/local/Kobo/') + 'imageformats/libnickelhome.so';
        const entries = parseTar(zlib.gunzipSync(await zip.file('.kobo/' + filename).async('nodebuffer')));
        const source = parseTar(zlib.gunzipSync(fs.readFileSync(path.join(WEBROOT, 'assets', major === '6' ? 'NickelHome-Qt6.tgz' : 'NickelHome.tgz'))));
        expect(entries[pluginPath]).toEqual(source[pluginPath]);
        expect(Object.keys(entries).filter((name) => name.endsWith('/libnickelhome.so'))).toEqual([pluginPath]);
        expect(zip.file('.kobo/' + (major === '6' ? 'KoboRoot.tgz' : 'Kobo.tgz'))).toBeNull();
        const config = await zip.file('.adds/nickel-home/config').async('string');
        expect(config).toContain('hide_home_row1col2_enabled:1');
        expect(config).toContain('hide_home_row3_enabled:1');
        expect(config).not.toContain('hide_home_row2col2_enabled:1');
        expect(zip.file('.adds/nickel-home/uninstall')).not.toBeNull();
        expect((await zip.file('.adds/nm/webui-preset').async('string')).match(/Minimal Home/g)).toHaveLength(1);
        const manifest = JSON.parse(await zip.file('.kobopatch-webui/nickelmenu.json').async('string'));
        expect(manifest.selected).toEqual(expect.arrayContaining([hiders[0], hiders[2]]));
        expect(manifest.features[hiders[0]].version).toBe('v0.7');
        if (major === '6') expect(Object.keys(entries).every((name) => !name.startsWith('usr/') && !name.startsWith('mnt/'))).toBe(true);
    });
}

for (const keepOne of [true, false]) {
    test(`OS 6 modifying NickelHome ${keepOne ? 'keeps its shared folder and restores its marker' : 'removes the mod when no hider remains'}`, async ({
        page,
    }) => {
        await connectMockDevice(page, {
            firmware: '6.0.279225',
            extraAddsFiles: [
                { path: ['nm', 'webui-preset'], content: '# Generated by KoboPatch Web UI\n' },
                {
                    path: ['nickel-home', 'config'],
                    content: 'nhm_enabled:1\nhide_home_row1col2_enabled:1\nhide_home_row2col2_enabled:1\nhide_home_row3_enabled:1\n',
                },
                { path: ['nickel-home', 'doc'], content: 'Keep the installed documentation' },
                { path: ['.nickel-home.initialized'], content: '1\n' },
            ],
            extraRootFiles: [{ path: ['.kobopatch-webui', 'nickelmenu.json'], content: JSON.stringify({ selected: ['custom-menu', ...hiders] }) }],
        });
        await goToNmFeatures(page);
        for (const id of hiders) {
            await expect(page.locator(`input[name="nm-cfg-${id}"]`)).toBeChecked();
            await page.locator(`input[name="nm-cfg-${id}"]`).setChecked(keepOne && id === hiders[2]);
        }
        await page.click('#btn-nm-features-next');
        await skipNmBackup(page);
        await page.click('#btn-nm-write');
        await expect(page.locator('#step-nm-done')).toBeVisible();
        expect(await mockPathExists(page, '.adds', 'nickel-home')).toBe(keepOne);
        expect(await readMockFile(page, '.adds', '.nickel-home.initialized')).toBe('1\n');
        if (keepOne) {
            expect(await readMockFile(page, '.adds', 'nickel-home', 'doc')).toBe('Keep the installed documentation');
            expect(await mockPathExists(page, '.adds', 'nickel-home', 'uninstall')).toBe(true);
            const config = await readMockFile(page, '.adds', 'nickel-home', 'config');
            expect(config).toContain('hide_home_row3_enabled:1');
            expect(config).not.toContain('hide_home_row1col2_enabled:1');
            expect(config).not.toContain('hide_home_row2col2_enabled:1');
        }
    });
}
